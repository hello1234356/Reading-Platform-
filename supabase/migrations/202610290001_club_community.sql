create function public.assign_club_general_channel() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.channel_id is null then select id into new.channel_id from public.club_channels where club_id=new.club_id and slug='general'; end if;
  return new;
end $$;
create trigger club_post_default_channel before insert on public.club_posts for each row execute function public.assign_club_general_channel();
-- Some early installations also retain club_messages. Copy only conversations
-- absent from the current table and retain the original table and IDs untouched.
do $$ begin
  if to_regclass('public.club_messages') is not null then
    insert into public.club_posts(club_id,user_id,message,created_at,channel_id)
    select m.club_id,m.user_id,m.message,m.created_at,c.id from public.club_messages m
      join public.club_channels c on c.club_id=m.club_id and c.slug='general'
    where not exists(select 1 from public.club_posts p where p.club_id=m.club_id and p.user_id=m.user_id and p.message=m.message and p.created_at=m.created_at);
  end if;
end $$;

