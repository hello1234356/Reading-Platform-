create function public.guard_club_integrity() returns trigger language plpgsql security definer set search_path=public as $$
declare v_capacity integer; v_host uuid;
begin
  if tg_table_name='book_clubs' then
    if new.creator_id is distinct from old.creator_id or new.id <> old.id then raise exception 'Club ownership and ID are immutable'; end if;
    if new.members_wanted < (select count(*) from public.club_members where club_id=new.id) then raise exception 'Capacity is below current membership'; end if;
    if new.members_wanted is null or new.members_wanted < 1 then raise exception 'Capacity must be positive'; end if;
    if (new.title,new.description,new.duration,new.members_wanted,new.tags,new.book_id,new.cover_url)
      is distinct from (old.title,old.description,old.duration,old.members_wanted,old.tags,old.book_id,old.cover_url) then
      new.updated_at=clock_timestamp();
    elsif current_setting('litshelf.saving_club_settings',true) is distinct from 'true' then new.updated_at=old.updated_at; end if;
    return new;
  elsif tg_op='INSERT' then
    -- This row lock serializes joins with capacity changes and other joins.
    select members_wanted,creator_id into v_capacity,v_host from public.book_clubs where id=new.club_id for update;
    if not exists(select 1 from public.club_members where club_id=new.club_id and user_id=new.user_id)
      and (select count(*) from public.club_members where club_id=new.club_id)>=v_capacity then raise exception 'Club is full'; end if;
    return new;
  elsif tg_op='DELETE' then
    select creator_id into v_host from public.book_clubs where id=old.club_id;
    if v_host=old.user_id then raise exception 'The host cannot leave their club'; end if;
    return old;
  end if;
  return new;
end $$;
create trigger club_settings_integrity before update on public.book_clubs for each row execute function public.guard_club_integrity();
create trigger club_membership_integrity before insert or delete on public.club_members for each row execute function public.guard_club_integrity();

create function public.guard_club_tag_limits() returns trigger language plpgsql security definer set search_path=public as $$
begin
  perform 1 from public.book_clubs where id=new.club_id for update;
  if tg_table_name='club_member_tags' then
    if (select count(*) from public.club_member_tags where club_id=new.club_id)>=20 then raise exception 'At most 20 member tags'; end if;
  else
    if (select count(*) from public.club_member_tag_assignments where club_id=new.club_id and user_id=new.user_id)>=3 then raise exception 'At most 3 selected tags'; end if;
  end if;
  return new;
end $$;
create trigger club_tag_limit before insert on public.club_member_tags for each row execute function public.guard_club_tag_limits();
create trigger club_tag_selection_limit before insert on public.club_member_tag_assignments for each row execute function public.guard_club_tag_limits();

-- Invoker rights retain all RLS checks. One transaction preserves club and stage
-- identities, updates the schedule, and rolls everything back on any failure.
create function public.save_club_settings(p_club_id bigint,p_expected_updated_at timestamptz,p_settings jsonb,p_schedule jsonb)
returns void language plpgsql security invoker set search_path=public as $$
declare v_club public.book_clubs%rowtype; v_stage jsonb; v_position integer:=0; v_ids bigint[]:='{}'; v_id bigint;
begin
  select * into v_club from public.book_clubs where id=p_club_id for update;
  if not found or v_club.creator_id is distinct from auth.uid() then raise exception 'Only the host can edit club settings'; end if;
  if v_club.updated_at is distinct from p_expected_updated_at then raise exception 'Club settings changed; reload before saving'; end if;
  if char_length(btrim(coalesce(p_settings->>'title',''))) not between 1 and 100
    or char_length(btrim(coalesce(p_settings->>'description',''))) not between 1 and 350
    or char_length(btrim(coalesce(p_settings->>'duration',''))) not between 1 and 100 then raise exception 'Invalid club information'; end if;
  if jsonb_typeof(p_settings->'tags')<>'array' or jsonb_array_length(p_settings->'tags')>10 then raise exception 'Invalid club tags'; end if;
  if exists(select 1 from jsonb_array_elements_text(p_settings->'tags') tag where char_length(btrim(tag)) not between 1 and 30) then raise exception 'Invalid club tag'; end if;
  if jsonb_typeof(p_schedule)<>'array' or jsonb_array_length(p_schedule)>52 then raise exception 'Invalid reading schedule'; end if;
  if not public.can_use_moderated_book((p_settings->>'book_id')::bigint) then raise exception 'Choose an approved book'; end if;
  update public.book_clubs set title=btrim(p_settings->>'title'),description=btrim(p_settings->>'description'),duration=btrim(p_settings->>'duration'),
    members_wanted=(p_settings->>'members_wanted')::integer,tags=array(select jsonb_array_elements_text(p_settings->'tags')),
    book_id=(p_settings->>'book_id')::bigint,
    cover_url=case when book_id<>(p_settings->>'book_id')::bigint then null else cover_url end
  where id=p_club_id;
  -- Temporary positive positions avoid unique(club_id,position) collisions.
  update public.club_schedule set position=position+1000000 where club_id=p_club_id;
  for v_stage in select value from jsonb_array_elements(p_schedule) loop
    v_position:=v_position+1;
    if char_length(btrim(coalesce(v_stage->>'title',''))) not between 1 and 100
      or char_length(coalesce(v_stage->>'chapters',''))>300 or char_length(coalesce(v_stage->>'description',''))>2000 then raise exception 'Invalid reading stage'; end if;
    v_id:=nullif(v_stage->>'id','')::bigint;
    if v_id is not null then
      if v_id=any(v_ids) then raise exception 'Duplicate reading stage'; end if;
      update public.club_schedule set position=v_position,title=btrim(v_stage->>'title'),chapters=v_stage->>'chapters',description=v_stage->>'description',updated_at=now() where id=v_id and club_id=p_club_id;
      if not found then raise exception 'Reading stage does not belong to this club'; end if;
    else
      insert into public.club_schedule(club_id,position,title,chapters,description) values(p_club_id,v_position,btrim(v_stage->>'title'),v_stage->>'chapters',v_stage->>'description') returning id into v_id;
    end if;
    v_ids:=array_append(v_ids,v_id);
  end loop;
  delete from public.club_schedule where club_id=p_club_id and not(id=any(v_ids));
  -- Force an edit timestamp even for a schedule-only change via a dedicated setting.
  perform set_config('litshelf.saving_club_settings','true',true);
  update public.book_clubs set updated_at=clock_timestamp() where id=p_club_id;
  perform set_config('litshelf.saving_club_settings','false',true);
end $$;
revoke all on function public.save_club_settings(bigint,timestamptz,jsonb,jsonb) from public;
grant execute on function public.save_club_settings(bigint,timestamptz,jsonb,jsonb) to authenticated;

