create or replace function public.is_club_host(p_club_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.book_clubs where id=p_club_id and creator_id=auth.uid()); $$;
create or replace function public.is_club_member(p_club_id bigint)
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.club_members where club_id=p_club_id and user_id=auth.uid()); $$;
revoke all on function public.is_club_host(bigint), public.is_club_member(bigint) from public;
grant execute on function public.is_club_host(bigint), public.is_club_member(bigint) to authenticated;

create table public.club_channels (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.book_clubs(id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9-]{1,40}$'),
  position integer not null default 0,
  created_at timestamptz not null default now(),
  unique(club_id,slug), unique(club_id,id)
);
insert into public.club_channels(club_id,slug,position)
select c.id,s.slug,s.position from public.book_clubs c cross join (values ('general',0),('spoiler-zone',1)) s(slug,position);
create function public.create_club_channels() returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.club_channels(club_id,slug,position) values(new.id,'general',0),(new.id,'spoiler-zone',1);
  return new;
end $$;
create trigger club_default_channels after insert on public.book_clubs for each row execute function public.create_club_channels();

alter table public.club_posts add column channel_id bigint;
